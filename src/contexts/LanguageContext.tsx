type LanguageCode = "en" | "sw";

type LanguageContextValue = {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: keyof typeof translations.en, params?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export { LanguageContext };

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    // Check both localStorage keys for backwards compatibility
    const storedPreference = typeof window !== "undefined" ? localStorage.getItem("language-preference") : null;
    const storedLegacy = typeof window !== "undefined" ? localStorage.getItem("language") : null;
    const stored = storedPreference || storedLegacy;

    if (stored === "sw" || stored === "en") {
      return stored;
    }
    // Default to English if no preference
    return "en";
  });

  const setLanguage = (nextLanguage: LanguageCode) => {
    setLanguageState(nextLanguage);
    if (typeof window !== "undefined") {
      // Store in preferred key
      localStorage.setItem("language-preference", nextLanguage);
      // Also update legacy key for backwards compatibility
      localStorage.setItem("language", nextLanguage);
    }
  };

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
    }
  }, [language]);

  // On an organization's white-label portal the product is that organization, not SENDA: every
  // "SENDA" / "SENDA Copilot" in a translated string becomes its name.
  const brand = useBranding();
  const brandName = brand.branded ? (brand.workspace_name || brand.display_name || "") : "";

  // Swahili is fetched only when it is the active language (English is bundled). Until it arrives
  // the English text is shown, so nothing is ever blank.
  const [swDictionary, setSwDictionary] = useState<Record<string, string> | null>(null);
  useEffect(() => {
    if (language !== "sw" || swDictionary) return;
    let live = true;
    import("@/i18n/sw").then((m) => live && setSwDictionary(m.default));
    return () => {
      live = false;
    };
  }, [language, swDictionary]);

  const t = useMemo(() => {
    const withBrand = (text: string) => (brandName ? text.replace(/\bSENDA(?: Copilot)?\b/g, () => brandName) : text);
    return (key: keyof typeof translations.en, params?: Record<string, string | number>) => {
      const base = (language === "sw" ? swDictionary?.[key] : undefined) || translations.en[key] || String(key);
      if (!params) {
        return withBrand(base);
      }
      return withBrand(Object.keys(params).reduce((result, paramKey) => {
        return result.replace(new RegExp(`{{${paramKey}}}`, "g"), String(params[paramKey]));
      }, base));
    };
  }, [language, brandName, swDictionary]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}
